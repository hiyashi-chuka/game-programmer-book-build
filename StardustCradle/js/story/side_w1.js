  async function speak(id, v, npc) {
    if (!v) return;
    if (typeof v === 'function') return v(npc);
    if (!Array.isArray(v)) v = [v];
    for (const line of v) {
      if (Array.isArray(line)) await E.say(line[0], line[1]);
      else await E.say(id, line);
    }
  }
